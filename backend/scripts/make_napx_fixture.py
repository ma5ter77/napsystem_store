"""NAP-104: writes frontend/scripts/fixtures/napx-v1.json — a package, a device key and a lease made by the server
code, so the browser implementation (frontend/lib/napx.ts) is tested against the very same bytes.

    cd backend && uv run python scripts/make_napx_fixture.py
"""
import base64
import hashlib
import io
import json
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
from cryptography.hazmat.primitives import serialization  # noqa: E402
from cryptography.hazmat.primitives.asymmetric import ec  # noqa: E402
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey  # noqa: E402

from app.secure import napx  # noqa: E402

OUT = os.path.join(os.path.dirname(__file__), "..", "..", "frontend", "scripts", "fixtures", "napx-v1.json")


def main() -> None:
    signer, device = Ed25519PrivateKey.generate(), ec.generate_private_key(ec.SECP256R1())
    plain = bytes((i * 31 + 7) % 256 for i in range(10_000))   # 3 segments of 4096 bytes, the last one short
    cek, buf = os.urandom(32), io.BytesIO()
    p = napx.write_package(io.BytesIO(plain), buf, cek=cek, signer=signer, content_id="fixture",
                           sha256=hashlib.sha256(plain).hexdigest(), size=len(plain), content_type="audio/flac",
                           key_id="fixture", segment_size=4096)
    lid = "00000000-0000-4000-8000-000000000104"
    payload = {"v": 1, "lid": lid, "sub": "u", "dev": "d", "app": "a", "ver": "v", "session": "s",
               "layout": "headphones", "content_id": "fixture", "sha256": hashlib.sha256(plain).hexdigest(),
               "manifest_sha256": p.manifest_sha256, "iat": 1762387200, "exp": 4102444800,
               "key": napx.seal_for_device(device.public_key(), cek, lid)}
    pub = signer.public_key().public_bytes(serialization.Encoding.Raw, serialization.PublicFormat.Raw)
    fixture = {
        "note": "test data only: generated by backend/scripts/make_napx_fixture.py",
        "signing_key": {"kid": "fixture", "alg": "EdDSA", "crv": "Ed25519", "x": napx.b64u(pub)},
        "device_pkcs8": base64.b64encode(device.private_bytes(serialization.Encoding.DER,
                                                              serialization.PrivateFormat.PKCS8,
                                                              serialization.NoEncryption())).decode(),
        "lease": napx.sign_lease(signer, "fixture", payload),
        "package": base64.b64encode(buf.getvalue()).decode(),
        "plaintext_sha256": hashlib.sha256(plain).hexdigest(),
        "segment_size": 4096,
    }
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as f:
        json.dump(fixture, f, indent=1)
        f.write("\n")
    print(os.path.relpath(OUT))


if __name__ == "__main__":
    main()
